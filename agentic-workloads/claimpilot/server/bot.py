def format_claim_id(sequence: int) -> str:
    return f"{CLAIM_ID_PREFIX}-{sequence}"


def current_claim_id() -> str:
    claim_id = str(CLAIM_STATE.get("claimId") or "")
    if claim_id.startswith(f"{CLAIM_ID_PREFIX}-"):
        return claim_id
    return format_claim_id(CLAIM_ID_START)


def claim_is_submitted() -> bool:
    return str(CLAIM_STATE.get("status") or "").lower() == "submitted"


async def next_claim_id() -> str:
    async with CLAIM_ID_LOCK:
        try:
            last_sequence = int(CLAIM_SEQUENCE_FILE.read_text(encoding="utf-8").strip())
        except (OSError, ValueError):
            last_sequence = CLAIM_ID_START - 1

        next_sequence = last_sequence + 1
        await asyncio.to_thread(
            CLAIM_SEQUENCE_FILE.write_text,
            str(next_sequence),
            encoding="utf-8",
        )
        return format_claim_id(next_sequence)


