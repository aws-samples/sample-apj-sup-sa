def evidence_image_format(s3_key: str, content_type: str = ""):
    normalized_content_type = content_type.split(";")[0].strip().lower()
    content_type_formats = {
        "image/jpeg": "jpeg",
        "image/jpg": "jpeg",
        "image/png": "png",
        "image/gif": "gif",
        "image/webp": "webp",
    }
    if normalized_content_type in content_type_formats:
        return content_type_formats[normalized_content_type]

    extension = s3_key.rsplit(".", 1)[-1].lower() if "." in s3_key else ""
    if extension in {"jpg", "jpeg"}:
        return "jpeg"
    if extension in {"png", "gif", "webp"}:
        return extension
    return "jpeg"


async def fetch_evidence_image(evidence: dict, diagnostic_actions: list[dict]):
    bucket = str(evidence.get("bucket") or EVIDENCE_BUCKET_NAME or "")
    s3_key = str(evidence.get("s3Key") or "")
    diagnostic_actions.append(
        tool_event(
            "s3_fetch_evidence_image",
            s3_key or "Waiting for S3 evidence key",
            "running",
        )
    )
    if not bucket or not s3_key:
        reason = "S3 evidence bucket/key not available"
        logger.debug(f"Skipping Bedrock image analysis; {reason}")
        diagnostic_actions.append(tool_event("s3_fetch_evidence_image", reason, "failed"))
        return None, reason

    s3 = get_aws_client("s3")
    if s3 is None:
        reason = "boto3 unavailable for S3 image fetch"
        logger.debug(f"Skipping Bedrock image analysis; {reason}")
        diagnostic_actions.append(tool_event("s3_fetch_evidence_image", reason, "failed"))
        return None, reason

    try:
        response = await asyncio.to_thread(s3.get_object, Bucket=bucket, Key=s3_key)
        image_bytes = await asyncio.to_thread(response["Body"].read)
    except Exception as exc:
        reason = f"S3 image fetch failed: {exc}"
        logger.warning(f"Evidence image fetch failed; using fallback: {exc}")
        diagnostic_actions.append(tool_event("s3_fetch_evidence_image", reason, "failed"))
        return None, reason

    storage = f"s3://{bucket}/{s3_key}"
    diagnostic_actions.extend(
        [
            tool_event("s3_fetch_evidence_image", storage, "complete"),
            aws_proof("S3", storage, "evidence image fetched"),
        ]
    )
    return {
        "bytes": image_bytes,
        "format": evidence_image_format(s3_key, str(response.get("ContentType", ""))),
    }, ""


def extract_json_object(text: str):
    decoder = json.JSONDecoder()
    stripped = text.strip()
    for start in (0, stripped.find("{")):
        if start < 0:
            continue
        try:
            value, _ = decoder.raw_decode(stripped[start:])
            if isinstance(value, dict):
                return value
        except json.JSONDecodeError:
            continue
    return None


def clean_string_list(value, fallback: list[str] | None = None):
    if not isinstance(value, list):
        return fallback or []
    return [str(item).strip() for item in value if str(item).strip()]


def normalize_license_plate(value):
    if not isinstance(value, dict):
        return {"visible": False, "text": None, "confidence": "low"}

    text = value.get("text")
    text = str(text).strip() if text is not None and str(text).strip() else None
    confidence = str(value.get("confidence") or "low").lower()
    if confidence not in {"high", "medium", "low"}:
        confidence = "low"

    return {
        "visible": bool(value.get("visible") or text),
        "text": text,
        "confidence": confidence,
    }


def normalize_evidence_analysis(raw_analysis: dict):
    visible_damage = clean_string_list(raw_analysis.get("visibleDamage"))
    vehicle_parts = clean_string_list(raw_analysis.get("vehicleParts"))
    license_plate = normalize_license_plate(raw_analysis.get("licensePlate"))
    missing_evidence = clean_string_list(raw_analysis.get("missingEvidence"))
    notes = clean_string_list(raw_analysis.get("notes"))
    adjuster_note = str(raw_analysis.get("adjusterNote") or "").strip()
    mismatch_reason = str(raw_analysis.get("mismatchReason") or "").strip()
    is_relevant = raw_analysis.get("isRelevant")
    if not isinstance(is_relevant, bool):
        severity_hint = str(raw_analysis.get("severity") or "").lower()
        is_relevant = bool(visible_damage or vehicle_parts) and severity_hint != "none"

    finding = str(raw_analysis.get("finding") or "").strip()
    if not finding:
        if not is_relevant:
            finding = "Photo does not show the requested vehicle damage"
        elif visible_damage and vehicle_parts:
            finding = f"{', '.join(vehicle_parts[:2]).title()} damage visible"
        elif visible_damage:
            finding = ", ".join(visible_damage[:2])
        else:
            finding = "Uploaded vehicle evidence analyzed for adjuster review"

    severity = str(raw_analysis.get("severity") or "Unknown").strip().title()
    if severity not in {"None", "Minor", "Moderate", "Severe", "Unknown"}:
        severity = "Unknown"

    if not is_relevant:
        notes.insert(0, mismatch_reason or "Photo does not match the requested damage evidence")
        missing_evidence.append("Matching damage photo")
        adjuster_note = adjuster_note or "Replacement photo requested before claim review."
    elif vehicle_parts and not any("part" in note.lower() for note in notes):
        notes.insert(0, f"Visible vehicle part(s): {', '.join(vehicle_parts[:4])}")

    if license_plate["visible"] and license_plate["text"]:
        notes.append(
            f"License plate detected: {license_plate['text']} ({license_plate['confidence']} confidence)"
        )
    elif license_plate["visible"]:
        notes.append(f"License plate visible but unreadable ({license_plate['confidence']} confidence)")
        missing_evidence.append("Readable license plate")
    else:
        notes.append("License plate not visible in photo")
        missing_evidence.append("License plate not visible")

    if adjuster_note:
        notes.append(adjuster_note)
    notes.extend(["Photo attached to adjuster packet", "Police report number still needed"])

    deduped_notes = []
    for note in notes:
        if note not in deduped_notes:
            deduped_notes.append(note)

    return {
        "finding": finding,
        "severity": severity,
        "notes": deduped_notes,
        "analysisProvider": f"Amazon Bedrock multimodal ({EVIDENCE_ANALYSIS_MODEL})",
        "visibleDamage": visible_damage,
        "vehicleParts": vehicle_parts,
        "licensePlate": license_plate,
        "missingEvidence": list(dict.fromkeys(missing_evidence)),
        "adjusterNote": adjuster_note or "Photo analyzed and attached for adjuster review.",
        "fallbackReason": "",
        "isRelevant": is_relevant,
        "mismatchReason": mismatch_reason,
    }


