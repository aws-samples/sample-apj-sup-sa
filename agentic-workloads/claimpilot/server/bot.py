def aws_runtime_api_enabled():
    return bool(AWS_RUNTIME_API_URL and AWS_RUNTIME_API_KEY)


def call_claimpilot_runtime_api_sync(action: str, payload: dict):
    if not aws_runtime_api_enabled():
        return None

    body = json.dumps({"action": action, "payload": payload}, default=str).encode("utf-8")
    request = urllib.request.Request(
        AWS_RUNTIME_API_URL,
        data=body,
        headers={
            "content-type": "application/json",
            "x-claimpilot-api-key": AWS_RUNTIME_API_KEY,
        },
        method="POST",
    )

    try:
        with urllib.request.urlopen(request, timeout=20) as runtime_response:
            response_body = runtime_response.read().decode("utf-8")
    except urllib.error.HTTPError as exc:
        error_body = exc.read().decode("utf-8", errors="replace")
        raise RuntimeError(f"runtime API {action} failed HTTP {exc.code}: {error_body}") from exc
    except Exception as exc:
        raise RuntimeError(f"runtime API {action} failed: {exc}") from exc

    try:
        return json.loads(response_body or "{}")
    except json.JSONDecodeError as exc:
        raise RuntimeError(f"runtime API {action} returned invalid JSON: {response_body[:300]}") from exc


async def call_claimpilot_runtime_api(action: str, payload: dict):
    return await asyncio.to_thread(call_claimpilot_runtime_api_sync, action, payload)


