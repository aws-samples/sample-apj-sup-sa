async def analyze_evidence_with_bedrock(
    evidence: dict,
    evidence_type: str,
    diagnostic_actions: list[dict],
):
    if EVIDENCE_ANALYSIS_MODE in {"demo", "fallback", "local", "mock", "none", "off"}:
        return None, f"evidence analysis mode is {EVIDENCE_ANALYSIS_MODE}"

    if EVIDENCE_ANALYSIS_MODE not in {"auto", "bedrock", "multimodal", "vision"}:
        reason = f"unknown evidence analysis mode {EVIDENCE_ANALYSIS_MODE}"
        logger.warning(f"Unknown evidence analysis mode {EVIDENCE_ANALYSIS_MODE}; using fallback")
        diagnostic_actions.append(tool_event("bedrock_vision_invoke", reason, "failed"))
        return None, reason

    if aws_runtime_api_enabled():
        diagnostic_actions.append(
            tool_event("claimpilot_runtime_api", "analyzeEvidence", "running")
        )
        try:
            result = await call_claimpilot_runtime_api(
                "analyzeEvidence",
                {
                    "evidence": evidence,
                    "evidenceType": evidence_type,
                    "s3Key": evidence.get("s3Key"),
                },
            )
        except Exception as exc:
            reason = f"AWS runtime API evidence analysis failed: {exc}"
            logger.warning(reason)
            diagnostic_actions.append(tool_event("claimpilot_runtime_api", reason, "failed"))
            return None, reason

        if result and result.get("ok") and isinstance(result.get("analysis"), dict):
            diagnostic_actions.extend(
                [
                    tool_event("claimpilot_runtime_api", "analyzeEvidence", "complete"),
                    aws_proof(
                        "Bedrock vision",
                        str(result.get("model") or "runtime API configured model"),
                        "image analysis result",
                    ),
                ]
            )
            return result["analysis"], ""

        reason = str((result or {}).get("reason") or "AWS runtime API evidence analysis failed")
        diagnostic_actions.append(tool_event("claimpilot_runtime_api", reason, "failed"))
        return None, reason

    if not EVIDENCE_ANALYSIS_MODEL:
        reason = "CLAIMPILOT_EVIDENCE_ANALYSIS_MODEL is not configured"
        logger.warning(f"Skipping Bedrock image analysis; {reason}")
        diagnostic_actions.append(tool_event("bedrock_vision_invoke", reason, "failed"))
        return None, reason

    image, fetch_reason = await fetch_evidence_image(evidence, diagnostic_actions)
    if image is None:
        return None, fetch_reason

    bedrock = get_aws_client("bedrock-runtime")
    if bedrock is None:
        reason = "boto3 unavailable for Bedrock vision invocation"
        logger.debug(f"Skipping Bedrock image analysis; {reason}")
        diagnostic_actions.append(tool_event("bedrock_vision_invoke", reason, "failed"))
        return None, reason

    diagnostic_actions.append(
        tool_event("bedrock_vision_invoke", EVIDENCE_ANALYSIS_MODEL, "running")
    )
    try:
        response = await asyncio.to_thread(
            bedrock.converse,
            modelId=EVIDENCE_ANALYSIS_MODEL,
            messages=[
                {
                    "role": "user",
                    "content": [
                        {"text": bedrock_evidence_prompt(evidence_type)},
                        {
                            "image": {
                                "format": image["format"],
                                "source": {"bytes": image["bytes"]},
                            }
                        },
                    ],
                }
            ],
            inferenceConfig={"maxTokens": 700, "temperature": 0},
        )
    except Exception as exc:
        reason = f"Bedrock vision invocation failed: {exc}"
        logger.warning(f"Bedrock image analysis failed; using fallback: {exc}")
        diagnostic_actions.append(tool_event("bedrock_vision_invoke", reason, "failed"))
        return None, reason

    content_blocks = response.get("output", {}).get("message", {}).get("content", [])
    response_text = "\n".join(
        str(block.get("text", "")) for block in content_blocks if block.get("text")
    )
    parsed = extract_json_object(response_text)
    if parsed is None:
        reason = f"Bedrock vision returned non-JSON response: {response_text[:300]}"
        logger.warning(f"Bedrock image analysis returned non-JSON response: {response_text[:300]}")
        diagnostic_actions.append(tool_event("bedrock_vision_parse", reason, "failed"))
        return None, reason

    diagnostic_actions.extend(
        [
            tool_event("bedrock_vision_invoke", EVIDENCE_ANALYSIS_MODEL, "complete"),
            aws_proof("Bedrock vision", EVIDENCE_ANALYSIS_MODEL, "image analysis result"),
        ]
    )
    return normalize_evidence_analysis(parsed), ""


