def normalize_claim_field_updates(raw_fields):
    updates = []
    for item in raw_fields or []:
        if not isinstance(item, dict):
            continue
        field = str(item.get("field") or "").strip()
        value = str(item.get("value") or "").strip()
        if field not in CLAIM_FIELD_NAMES or not value:
            continue
        updates.append(
            {
                "field": field,
                "value": value,
                "status": str(item.get("status") or "Captured"),
                "note": str(item.get("note") or "Captured from voice"),
            }
        )
    return updates


