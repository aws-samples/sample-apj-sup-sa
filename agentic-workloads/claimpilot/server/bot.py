def get_dynamodb_table():
    if boto3 is None or not CLAIMS_TABLE_NAME:
        return None

    cache_key = f"dynamodb-table:{CLAIMS_TABLE_NAME}"
    if cache_key not in AWS_CLIENTS:
        resource = boto3.resource("dynamodb", region_name=os.getenv("AWS_REGION"))
        AWS_CLIENTS[cache_key] = resource.Table(CLAIMS_TABLE_NAME)

    return AWS_CLIENTS[cache_key]


def claim_state_snapshot():
    return json.loads(json.dumps(CLAIM_STATE, default=str))


async def persist_claim_state(status: str = "Draft"):
    CLAIM_STATE["status"] = status
    CLAIM_STATE["updatedAt"] = utc_now_iso()
    snapshot = claim_state_snapshot()

    if aws_runtime_api_enabled():
        try:
            result = await call_claimpilot_runtime_api(
                "persistClaimState",
                {
                    "claimId": CLAIM_STATE["claimId"],
                    "status": CLAIM_STATE["status"],
                    "updatedAt": CLAIM_STATE["updatedAt"],
                    "claimState": snapshot,
                },
            )
            if result and result.get("ok"):
                logger.info(f"Persisted claim state through AWS runtime API: {CLAIM_STATE['claimId']}")
                return result
            logger.warning(f"AWS runtime API claim persistence failed; continuing: {result}")
            return result or {"ok": False, "reason": "AWS runtime API returned no result"}
        except Exception as exc:
            logger.warning(f"AWS runtime API claim persistence failed; continuing locally: {exc}")

    table = get_dynamodb_table()
    if table is None:
        logger.debug("Skipping DynamoDB persistence; no table configured")
        return {"ok": False, "reason": "DynamoDB table not configured"}

    item = {
        "claimId": CLAIM_STATE["claimId"],
        "status": CLAIM_STATE["status"],
        "claimState": snapshot,
        "fields": CLAIM_STATE["fields"],
        "missingInformation": CLAIM_STATE["missingInformation"],
        "evidence": CLAIM_STATE["evidence"],
        "updatedAt": CLAIM_STATE["updatedAt"],
    }
    for key in (
        "claimType",
        "incidentSummary",
        "safetySummary",
        "adjusterSummary",
        "awsProof",
        "claimSummary",
        "customerSummary",
        "faultAndExcessEstimate",
        "recommendedNextAction",
        "supervisor",
        "timeline",
        "finalPacket",
        "finalPacketStorage",
    ):
        if key in CLAIM_STATE:
            item[key] = CLAIM_STATE[key]

    try:
        await asyncio.to_thread(table.put_item, Item=item)
        logger.info(f"Persisted claim state to DynamoDB: {CLAIM_STATE['claimId']}")
        return {"ok": True, "table": CLAIMS_TABLE_NAME}
    except Exception as exc:
        logger.warning(f"DynamoDB persistence failed; continuing with local state: {exc}")
        return {"ok": False, "reason": str(exc)}


def cancel_pending_claim_persistence():
    global PENDING_PERSIST_TASK

    if PENDING_PERSIST_TASK and not PENDING_PERSIST_TASK.done():
        PENDING_PERSIST_TASK.cancel()
    PENDING_PERSIST_TASK = None


async def run_debounced_claim_persistence(status: str):
    try:
        await asyncio.sleep(max(PERSIST_DEBOUNCE_MS, 0) / 1000)
        await persist_claim_state(status)
    except asyncio.CancelledError:
        logger.debug("Cancelled pending debounced claim persistence")
        raise


def queue_claim_persistence(status: str = "Draft"):
    """Queue non-durable draft persistence without blocking the voice response path."""
    global PENDING_PERSIST_TASK

    CLAIM_STATE["status"] = status
    CLAIM_STATE["updatedAt"] = utc_now_iso()
    cancel_pending_claim_persistence()

    try:
        PENDING_PERSIST_TASK = asyncio.create_task(run_debounced_claim_persistence(status))
    except RuntimeError as exc:
        logger.debug(f"Could not queue claim persistence outside an event loop: {exc}")
        return {"ok": False, "queued": False, "reason": str(exc)}

    return {"ok": True, "queued": True, "debounceMs": PERSIST_DEBOUNCE_MS}


async def persist_claim_state_for_tool(status: str = "Draft", *, durable: bool = False):
    if durable or status != "Draft":
        cancel_pending_claim_persistence()
        return await persist_claim_state(status)
    return queue_claim_persistence(status)


def safe_s3_name(value: str):
    safe = "".join(char if char.isalnum() else "-" for char in value.lower()).strip("-")
    return safe or "evidence"


def normalized_upload_content_type(content_type: str = ""):
    normalized = content_type.split(";")[0].strip().lower()
    if normalized in {"image/jpeg", "image/jpg"}:
        return "image/jpeg"
    if normalized in {"image/png", "image/webp", "image/gif"}:
        return normalized
    return "image/jpeg"


def extension_for_content_type(content_type: str):
    return {
        "image/png": "png",
        "image/webp": "webp",
        "image/gif": "gif",
    }.get(content_type, "jpg")


def build_presigned_upload(requested_evidence: str, content_type: str = ""):
    upload_content_type = normalized_upload_content_type(content_type)
    evidence_id = f"ev-{uuid4().hex[:10]}"
    safe_name = safe_s3_name(requested_evidence)
    extension = extension_for_content_type(upload_content_type)
    claim_id = current_claim_id()
    s3_key = f"claims/{claim_id}/evidence/{evidence_id}-{safe_name}.{extension}"

    if aws_runtime_api_enabled():
        try:
            result = call_claimpilot_runtime_api_sync(
                "createEvidenceUpload",
                {
                    "claimId": claim_id,
                    "requestedEvidence": requested_evidence,
                    "contentType": upload_content_type,
                    "evidenceId": evidence_id,
                    "s3Key": s3_key,
                },
            )
            if result:
                return {
                    "evidenceId": result.get("evidenceId", evidence_id),
                    "s3Key": result.get("s3Key", s3_key),
                    "uploadUrl": result.get("uploadUrl"),
                    "bucket": result.get("bucket"),
                    "storage": result.get("storage") or f"local-demo://{s3_key}",
                    "contentType": result.get("contentType", upload_content_type),
                }
        except Exception as exc:
            logger.warning(f"AWS runtime API presigned upload failed; falling back locally: {exc}")

    if not EVIDENCE_BUCKET_NAME:
        return {
            "evidenceId": evidence_id,
            "s3Key": s3_key,
            "uploadUrl": None,
            "bucket": None,
            "storage": f"local-demo://{s3_key}",
            "contentType": upload_content_type,
        }

    s3 = get_aws_client("s3")
    if s3 is None:
        return {
            "evidenceId": evidence_id,
            "s3Key": s3_key,
            "uploadUrl": None,
            "bucket": EVIDENCE_BUCKET_NAME,
            "storage": f"s3://{EVIDENCE_BUCKET_NAME}/{s3_key}",
            "contentType": upload_content_type,
        }

    try:
        upload_url = s3.generate_presigned_url(
            "put_object",
            Params={
                "Bucket": EVIDENCE_BUCKET_NAME,
                "Key": s3_key,
                "ContentType": upload_content_type,
            },
            ExpiresIn=PRESIGNED_UPLOAD_EXPIRES_SECONDS,
        )
    except Exception as exc:
        logger.warning(f"Failed to generate presigned S3 upload URL: {exc}")
        upload_url = None

    return {
        "evidenceId": evidence_id,
        "s3Key": s3_key,
        "uploadUrl": upload_url,
        "bucket": EVIDENCE_BUCKET_NAME,
        "storage": f"s3://{EVIDENCE_BUCKET_NAME}/{s3_key}",
        "contentType": upload_content_type,
    }


def get_event_detail(message: dict):
    payload = message.get("payload")
    if isinstance(payload, dict):
        return {**payload, **message}
    return message


def find_evidence_record(evidence_id: str = "", s3_key: str = ""):
    evidence_list = CLAIM_STATE.setdefault("evidence", [])

    for evidence in evidence_list:
        if evidence_id and evidence.get("evidenceId") == evidence_id:
            return evidence
        if s3_key and evidence.get("s3Key") == s3_key:
            return evidence

    if evidence_list:
        return evidence_list[0]

    evidence = {"evidenceId": evidence_id or f"ev-{uuid4().hex[:10]}"}
    evidence_list.append(evidence)
    return evidence


async def mark_evidence_uploaded(message: dict):
    detail = get_event_detail(message)
    evidence_id = str(detail.get("evidenceId") or "")
    s3_key = str(detail.get("s3Key") or "")
    storage = str(detail.get("storage") or "")
    file_name = str(detail.get("fileName") or "")
    content_type = str(detail.get("contentType") or "")
    file_size = detail.get("fileSize")

    evidence = find_evidence_record(evidence_id=evidence_id, s3_key=s3_key)
    if evidence_id:
        evidence["evidenceId"] = evidence_id
    if s3_key:
        evidence["s3Key"] = s3_key
    if EVIDENCE_BUCKET_NAME and s3_key:
        evidence["bucket"] = EVIDENCE_BUCKET_NAME
        storage = storage or f"s3://{EVIDENCE_BUCKET_NAME}/{s3_key}"
    if storage:
        evidence["storage"] = storage
    if file_name:
        evidence["fileName"] = file_name
    if content_type:
        evidence["contentType"] = content_type
    if isinstance(file_size, int):
        evidence["fileSize"] = file_size

    evidence["status"] = "Uploaded"
    evidence["uploadedAt"] = utc_now_iso()

    logger.info(
        "Registered evidence upload completion "
        f"evidenceId={evidence.get('evidenceId')} s3Key={evidence.get('s3Key')}"
    )
    return await persist_claim_state_for_tool("Draft")


