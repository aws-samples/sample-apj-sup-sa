def env_bool(name: str, default: bool) -> bool:
    value = os.getenv(name)
    if value is None:
        return default
    return value.lower() in ("true", "1", "yes", "y", "on")


def env_float(name: str, default: float) -> float:
    try:
        return float(os.getenv(name, str(default)))
    except ValueError:
        logger.warning(f"Invalid float for {name}; using {default}")
        return default


def env_int(name: str, default: int) -> int:
    try:
        return int(os.getenv(name, str(default)))
    except ValueError:
        logger.warning(f"Invalid integer for {name}; using {default}")
        return default


def env_clamped_float(name: str, default: float, minimum: float, maximum: float) -> float:
    value = env_float(name, default)
    if value < minimum or value > maximum:
        clamped = min(maximum, max(minimum, value))
        logger.warning(f"{name}={value} outside {minimum}-{maximum}; using {clamped}")
        return clamped
    return value


def env_optional_float(name: str):
    value = os.getenv(name)
    if value is None or value.strip() == "":
        return None
    try:
        return float(value)
    except ValueError:
        logger.warning(f"Invalid float for {name}; ignoring value")
        return None


