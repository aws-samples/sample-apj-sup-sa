class ClaimPilotSpeechTimeoutUserTurnStopStrategy(SpeechTimeoutUserTurnStopStrategy):
    """Speech-timeout strategy with Deepgram VAD event fallback.

    Browser/Daily audio-level events can look healthy even when local VAD is a
    little too strict. Deepgram still emits UserStarted/UserStopped frames, so
    treat those as a secondary turn boundary source for demo reliability.
    """

    async def process_frame(self, frame):
        result = await super().process_frame(frame)

        if isinstance(frame, UserStartedSpeakingFrame):
            await self._handle_vad_user_started_speaking(frame)
        elif isinstance(frame, UserStoppedSpeakingFrame):
            self._vad_user_speaking = False
            self._stop_secs = env_float("CLAIMPILOT_DEEPGRAM_VAD_STOP_SECS", self._stop_secs)
            self._vad_stopped_time = time.time()
            if self._text and self._timeout_task is None:
                timeout = self._calculate_timeout()
                self._timeout_task = self.task_manager.create_task(
                    self._timeout_handler(timeout), f"{self}::_timeout_handler"
                )
                await asyncio.sleep(0)
        elif (
            isinstance(frame, TranscriptionFrame)
            and self._text
            and not self._vad_user_speaking
            and self._vad_stopped_time is not None
            and self._timeout_task is None
        ):
            await self._maybe_trigger_user_turn_stopped()

        return result


def should_log_message(message: str) -> bool:
    return not any(
        marker in message
        for marker in ("[Pipecat:localAudioLevel]", "[Pipecat:remoteAudioLevel]")
    )


class InterceptHandler(logging.Handler):
    """Route stdlib logs from SDKs through Loguru's console sink."""

    def emit(self, record):
        if not should_log_message(record.getMessage()):
            return

        try:
            level = logger.level(record.levelname).name
        except ValueError:
            level = record.levelno

        logger.opt(depth=6, exception=record.exc_info).log(level, record.getMessage())


class CloudWatchLogSink:
    """Small Loguru sink that sends runtime logs to CloudWatch Logs when configured."""

    def __init__(self, log_group: str, log_stream: str):
        self.log_group = log_group
        self.log_stream = log_stream
        self.sequence_token = None
        self.enabled = False
        self.client = None

        if boto3 is None:
            self._warn("boto3 unavailable; CloudWatch logging disabled")
            return

        try:
            from botocore.config import Config

            self.client = boto3.client(
                "logs",
                region_name=os.getenv("AWS_REGION"),
                config=Config(
                    connect_timeout=1,
                    read_timeout=1,
                    retries={"max_attempts": 1},
                ),
            )
            self._ensure_log_group()
            self._ensure_log_stream()
            self.enabled = True
        except Exception as exc:
            self._warn(f"CloudWatch logging disabled: {exc}")

    def _warn(self, message: str):
        if not TERMINAL_LOGGING_DISABLED:
            sys.stderr.write(f"{message}\n")

    def _ensure_log_group(self):
        try:
            self.client.create_log_group(logGroupName=self.log_group)
        except self.client.exceptions.ResourceAlreadyExistsException:
            pass
        except Exception as exc:
            self.enabled = False
            raise RuntimeError(f"create log group failed: {exc}") from exc

    def _ensure_log_stream(self):
        try:
            self.client.create_log_stream(
                logGroupName=self.log_group,
                logStreamName=self.log_stream,
            )
        except self.client.exceptions.ResourceAlreadyExistsException:
            pass
        except Exception as exc:
            self.enabled = False
            raise RuntimeError(f"create log stream failed: {exc}") from exc

        self._refresh_sequence_token()

    def _refresh_sequence_token(self):
        response = self.client.describe_log_streams(
            logGroupName=self.log_group,
            logStreamNamePrefix=self.log_stream,
            limit=1,
        )
        for stream in response.get("logStreams", []):
            if stream.get("logStreamName") == self.log_stream:
                self.sequence_token = stream.get("uploadSequenceToken")
                break

    def __call__(self, message):
        if not self.enabled or self.client is None:
            return

        record = message.record
        event = {
            "timestamp": int(record["time"].timestamp() * 1000),
            "message": str(message).rstrip(),
        }
        kwargs = {
            "logGroupName": self.log_group,
            "logStreamName": self.log_stream,
            "logEvents": [event],
        }
        if self.sequence_token:
            kwargs["sequenceToken"] = self.sequence_token

        try:
            response = self.client.put_log_events(**kwargs)
            self.sequence_token = response.get("nextSequenceToken")
        except Exception:
            try:
                self._refresh_sequence_token()
                if self.sequence_token:
                    kwargs["sequenceToken"] = self.sequence_token
                response = self.client.put_log_events(**kwargs)
                self.sequence_token = response.get("nextSequenceToken")
            except Exception:
                self.enabled = False


def configure_cloudwatch_logging():
    if not CLOUDWATCH_LOG_GROUP_NAME:
        return

    cloudwatch_sink = CloudWatchLogSink(
        log_group=CLOUDWATCH_LOG_GROUP_NAME,
        log_stream=CLOUDWATCH_LOG_STREAM_NAME,
    )
    if not cloudwatch_sink.enabled:
        return

    cloudwatch_format = (
        "{time:YYYY-MM-DDTHH:mm:ss.SSSZ} | {level:<8} | "
        "{name}:{function}:{line} - {message}"
    )
    logger.add(
        cloudwatch_sink,
        level=CLOUDWATCH_LOG_LEVEL,
        format=cloudwatch_format,
        filter=lambda record: should_log_message(record["message"]),
        backtrace=False,
        diagnose=False,
    )
    logger.info(
        "CloudWatch logging enabled "
        f"group={CLOUDWATCH_LOG_GROUP_NAME} stream={CLOUDWATCH_LOG_STREAM_NAME}"
    )


def configure_console_logging():
    if TERMINAL_LOGGING_DISABLED:
        logger.remove()
        logging.root.handlers = []
        logging.disable(logging.CRITICAL)
        configure_cloudwatch_logging()
        return

    logging.disable(logging.NOTSET)

    log_level = TERMINAL_LOG_LEVEL
    log_format = (
        "<green>{time:HH:mm:ss.SSS}</green> | <level>{level: <8}</level> | "
        "<cyan>{name}</cyan>:<cyan>{function}</cyan>:<cyan>{line}</cyan> - "
        "<level>{message}</level>"
    )

    logger.remove()
    logger.add(
        sys.stderr,
        level=log_level,
        format=log_format,
        filter=lambda record: should_log_message(record["message"]),
        enqueue=True,
        backtrace=True,
        diagnose=False,
    )

    logging.root.handlers = [InterceptHandler()]
    logging.root.setLevel(log_level)
    for logger_name in ("deepgram", "websockets", "httpx", "httpcore"):
        logging.getLogger(logger_name).setLevel(log_level)

    logger.info(f"Console logging enabled at {log_level}")
    configure_cloudwatch_logging()


