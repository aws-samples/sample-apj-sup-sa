async def store_final_packet(final_packet: dict):
    if aws_runtime_api_enabled():
        try:
            result = await call_claimpilot_runtime_api(
                "storeFinalPacket",
                {
                    "claimId": final_packet.get("claimId"),
                    "finalPacket": final_packet,
                },
            )
            if result and result.get("ok"):
                logger.info(f"Stored final claim packet through AWS runtime API: {result.get('storage')}")
                return result
            logger.warning(f"AWS runtime API final packet storage failed; continuing: {result}")
            return result or {"ok": False, "reason": "AWS runtime API returned no result"}
        except Exception as exc:
            logger.warning(f"AWS runtime API final packet storage failed; falling back locally: {exc}")

    if not FINAL_PACKET_BUCKET_NAME:
        logger.debug("Skipping final packet S3 storage; no bucket configured")
        return {"ok": False, "reason": "S3 final packet bucket not configured"}

    s3 = get_aws_client("s3")
    if s3 is None:
        logger.debug("Skipping final packet S3 storage; boto3 unavailable")
        return {"ok": False, "reason": "boto3 unavailable"}

    s3_key = f"claims/{final_packet['claimId']}/final-packet.json"
    body = json.dumps(final_packet, indent=2, default=str).encode("utf-8")
    try:
        await asyncio.to_thread(
            s3.put_object,
            Bucket=FINAL_PACKET_BUCKET_NAME,
            Key=s3_key,
            Body=body,
            ContentType="application/json",
        )
    except Exception as exc:
        logger.warning(f"Final packet S3 storage failed; continuing: {exc}")
        return {"ok": False, "reason": str(exc)}

    storage = f"s3://{FINAL_PACKET_BUCKET_NAME}/{s3_key}"
    logger.info(f"Stored final claim packet in S3: {storage}")
    return {"ok": True, "bucket": FINAL_PACKET_BUCKET_NAME, "s3Key": s3_key, "storage": storage}


