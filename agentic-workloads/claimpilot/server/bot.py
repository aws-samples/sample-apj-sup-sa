class ClaimPilotTTSAudioRateProcessor(FrameProcessor):
    """Adjust Pipecat cascade TTS playback speed before transport output."""

    def __init__(self, playback_rate: float):
        super().__init__(name="claimpilot_tts_audio_rate")
        self.playback_rate = playback_rate

    async def process_frame(self, frame: Frame, direction: FrameDirection):
        await super().process_frame(frame, direction)

        if (
            direction == FrameDirection.DOWNSTREAM
            and isinstance(frame, TTSAudioRawFrame)
            and abs(self.playback_rate - 1.0) > 0.001
        ):
            adjusted = TTSAudioRawFrame(
                frame.audio,
                sample_rate=max(1, round(frame.sample_rate * self.playback_rate)),
                num_channels=frame.num_channels,
                context_id=frame.context_id,
            )
            adjusted.pts = frame.pts
            adjusted.metadata = dict(frame.metadata)
            adjusted.transport_destination = frame.transport_destination
            await self.push_frame(adjusted, direction)
            return

        await self.push_frame(frame, direction)


