async def handle_app_event(raw_message: str):
    try:
        message = json.loads(raw_message)
    except json.JSONDecodeError:
        logger.debug(f"Ignoring non-JSON browser event: {raw_message}")
        return

    if isinstance(message, list):
        for item in message:
            if isinstance(item, dict):
                await handle_app_event(json.dumps(item))
        return

    if not isinstance(message, dict):
        logger.debug(f"Ignoring unsupported browser event: {message}")
        return

    action = str(message.get("action") or message.get("type") or "")
    if action == "secure_handoff_completed":
        await mark_secure_handoff_completed(message)
    elif action == "manual_evidence_upload_requested":
        await prepare_manual_evidence_upload(message)
    elif action == "evidence_upload_completed":
        await mark_evidence_uploaded(message)
        detail = get_event_detail(message)
        evidence_type = str(
            detail.get("requestedEvidence")
            or detail.get("evidenceType")
            or "uploaded vehicle damage photo"
        )
        evidence_id = str(detail.get("evidenceId") or "")
        s3_key = str(detail.get("s3Key") or "")
        analysis = await analyze_evidence_core(
            evidence_type=evidence_type,
            evidence_id=evidence_id,
            s3_key=s3_key,
        )
        await publish_ui_actions(analysis["uiActions"])
        if analysis.get("isRelevant", True):
            await queue_app_context_message(
                "Evidence upload completed in the Northstar app and photo analysis is "
                f"back. Result: {analysis['finding']}. Severity: {analysis['severity']}. "
                "Tell the customer the result is attached, then continue to police "
                "report or review without asking them to upload again."
            )
        else:
            await queue_app_context_message(
                "Evidence upload completed in the Northstar app, but photo validation says "
                f"it does not match the requested claim damage. Result: {analysis['finding']}. "
                "Briefly tell the customer the photo is not the damaged bumper photo and ask "
                "them to upload the correct damage photo."
            )
    elif action == "evidence_upload_failed":
        await mark_evidence_upload_failed(message)
    else:
        logger.debug(f"Ignoring browser event action={action}")


async def ui_event_handler(websocket, _path=None):
    UI_EVENT_CLIENTS.add(websocket)
    logger.info(f"ClaimPilot UI event client connected: {len(UI_EVENT_CLIENTS)} active")
    try:
        async for message in websocket:
            await handle_app_event(message)
    finally:
        UI_EVENT_CLIENTS.discard(websocket)
        logger.info(f"ClaimPilot UI event client disconnected: {len(UI_EVENT_CLIENTS)} active")


async def ensure_ui_event_server():
    global UI_EVENT_SERVER

    if UI_EVENT_SERVER is not None:
        return UI_EVENT_SERVER

    if websockets is None:
        logger.warning("websockets package unavailable; UI actions will only be logged")
        return None

    try:
        UI_EVENT_SERVER = await websockets.serve(ui_event_handler, UI_EVENT_HOST, UI_EVENT_PORT)
    except OSError as exc:
        logger.warning(f"Could not start ClaimPilot UI event WebSocket; continuing: {exc}")
        return None

    logger.info(f"ClaimPilot UI event WebSocket listening on ws://{UI_EVENT_HOST}:{UI_EVENT_PORT}")
    return UI_EVENT_SERVER


async def publish_ui_actions(actions: list[dict]):
    if not actions:
        return

    message = json.dumps(actions[0] if len(actions) == 1 else actions)
    logger.info(f"Publishing UI actions: {message}")

    if not UI_EVENT_CLIENTS:
        logger.debug("No ClaimPilot UI WebSocket clients connected")
        return

    stale_clients = []
    for websocket in list(UI_EVENT_CLIENTS):
        try:
            await websocket.send(message)
        except Exception as exc:
            logger.warning(f"Failed to publish UI action to browser client: {exc}")
            stale_clients.append(websocket)

    for websocket in stale_clients:
        UI_EVENT_CLIENTS.discard(websocket)


async def queue_app_context_message(content: str):
    """Append a browser/app event to the LLM context and trigger a response."""
    if ACTIVE_PIPELINE_TASK is None:
        logger.debug(f"No active Pipecat task for app event context: {content}")
        return False

    message = {
        "role": "user",
        "content": f"[ClaimPilot app event] {content}",
    }
    await ACTIVE_PIPELINE_TASK.queue_frames(
        [LLMMessagesAppendFrame(messages=[message], run_llm=True)]
    )
    return True


