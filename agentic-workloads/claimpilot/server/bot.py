async def sync_claim_intake(params: FunctionCallParams):
    updates = normalize_claim_field_updates(params.arguments.get("fields", []))
    incident_summary = str(params.arguments.get("incidentSummary") or "").strip()
    safety_summary = str(params.arguments.get("safetySummary") or "").strip()
    missing_fields = [
        str(item).strip()
        for item in params.arguments.get("missingFields", [])
        if str(item).strip()
    ]
    timeline_events = normalize_timeline_events(params.arguments.get("timelineEvents", []))
    supervisor_update = params.arguments.get("supervisor")
    supervisor_update = supervisor_update if isinstance(supervisor_update, dict) else {}

    logger.info(
        "Function call sync_claim_intake "
        f"fields={json.dumps(updates)} incidentSummary={incident_summary} "
        f"safetySummary={safety_summary} missingFields={missing_fields}"
    )

    for item in updates:
        CLAIM_STATE["fields"][item["field"]] = item["value"]

    if incident_summary:
        CLAIM_STATE["claimType"] = "Auto accident"
        CLAIM_STATE["incidentSummary"] = incident_summary
        CLAIM_STATE["claimSummary"] = incident_summary
    if safety_summary:
        CLAIM_STATE["safetySummary"] = safety_summary
    if missing_fields:
        CLAIM_STATE["missingInformation"] = missing_fields
    if timeline_events:
        CLAIM_STATE["timeline"] = timeline_events

    current_supervisor = CLAIM_STATE.get("supervisor") or {}
    if supervisor_update or missing_fields:
        supervisor = {
            **current_supervisor,
            **supervisor_update,
        }
        if missing_fields and "blockers" not in supervisor_update:
            supervisor["blockers"] = missing_fields
        CLAIM_STATE["supervisor"] = supervisor
    else:
        supervisor = current_supervisor

    payload_preview = ", ".join(
        f"{item['field']}: {item['value']}" for item in updates
    )
    detail_parts = []
    if updates:
        detail_parts.append(f"{len(updates)} fields")
    if incident_summary or safety_summary:
        detail_parts.append("summaries")
    if timeline_events:
        detail_parts.append(f"{len(timeline_events)} timeline events")
    if missing_fields:
        detail_parts.append(f"{len(missing_fields)} missing items")
    detail = "Synced " + ", ".join(detail_parts) if detail_parts else "Intake state checked"

    ui_actions = [
        tool_event("sync_claim_intake", detail, payloadPreview=payload_preview),
    ]
    if updates:
        ui_actions.append(ui_action("update_claim_fields", fields=updates))
    if incident_summary or safety_summary:
        ui_actions.append(
            ui_action(
                "open_claim_details",
                screen="ClaimDetails",
                incidentSummary=incident_summary or CLAIM_STATE.get("incidentSummary", ""),
                safetySummary=safety_summary or CLAIM_STATE.get("safetySummary", ""),
            )
        )
        ui_actions.append(
            ui_action(
                "update_claim_summary",
                summary=incident_summary or CLAIM_STATE.get("claimSummary", ""),
                customerSummary=incident_summary or CLAIM_STATE.get("customerSummary", ""),
            )
        )
    if timeline_events:
        ui_actions.append(ui_action("update_timeline", events=timeline_events))
    for field in missing_fields:
        ui_actions.append(ui_action("highlight_missing", field=field))
    if supervisor_update or missing_fields:
        ui_actions.append(supervisor_state(**supervisor))

    persistence = await persist_claim_state_for_tool("Draft")
    await publish_ui_actions(ui_actions)
    await params.result_callback(
        {
            "ok": True,
            "fields": updates,
            "incidentSummary": incident_summary,
            "safetySummary": safety_summary,
            "missingFields": missing_fields,
            "timelineEvents": timeline_events,
            "supervisor": supervisor,
            "persistence": persistence,
            "uiActions": ui_actions,
        }
    )


