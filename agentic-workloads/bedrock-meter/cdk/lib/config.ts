export interface BedrockMeterConfig {
  bedrockRegion: string;
  logGroupName: string;
  logRetentionDays: number;
  allowBedrockLoggingOverwrite: boolean;
  deleteBedrockLoggingOnStackRemoval: boolean;

  adminEmails: string[];
  adminUsernames: string[];

  usageTableName: string;
  configTableName: string;
  auditTableName: string;
  usageRetentionDays: number;
  auditRetentionDays: number;
  defaultDailyCreditLimit: number;
  defaultWeeklyCreditLimit: number;
  defaultMonthlyCreditLimit: number;
  metricNamespace: string;
  initialQuotaTimeZone: string;
  roleEnforcementEnabled: boolean;
  createRegionGuardrailPolicy: boolean;
  analyticsDatabaseName: string;
  analyticsTableName: string;
  athenaWorkgroupName: string;
  alertsTopicName: string;
  alertsDisplayName: string;
  dashboardName: string;
  enableDashboard: boolean;
  coreApiName: string;

  // Console deployment + auth
  consoleApiName: string;
  // Pinned IAM role name for the console BFF Lambda. Core accepts this role name as an admin
  // CALLER (ADMIN_ROLE_NAMES) so the BFF can SigV4 with its own execution-role creds instead
  // of long-lived IAM-user signing keys. Pinned (not CDK-autogenerated) so the name is stable
  // across redeploys and both constructs can reference it without a circular dependency.
  consoleBffRoleName: string;
  // Two-tier console auth, by Cognito group (membership managed at runtime → no redeploy):
  //   consoleAdminGroup  (console-admins):  full read + write.
  //   consoleViewerGroup (console-viewers): read-only.
  // Optional emergency admin allowlist. Keep empty for normal operation; Cognito groups are
  // the steady-state authorization source.
  consoleAdminGroup: string;
  consoleViewerGroup: string;
  consoleAllowedUsers: string[];
  // false → GET reads are anonymous/public (the whole org's usage, IAM ARNs, limits, blocked
  // list, and audit log incl. operator [by email] attribution become world-readable through
  // the BFF's admin-equivalent role on a public no-authorizer HTTP API). Writes are ALWAYS
  // admin-only regardless. Default true (every data path requires a logged-in viewer/admin).
  consoleRequireAuthForReads: boolean;
  consoleUserPoolName: string;
}

